    @Test fun incompleteDroppedMissingAndSupersededSecretsAreRejected() {
        val manifest = seed()
        val asset = secrets.currentAsset("source")!!
        val state = artifacts.read("source") as CaptureArtifactState.Present
        for (bad in listOf(manifest.copy(packetDrops = 1), manifest.copy(interrupted = true),
            manifest.copy(finalized = false), manifest.copy(tls = manifest.tls.copy(complete = false)),
            manifest.copy(secretsPersistedSequence = 2))) {
            fails { TlsCaptureExportPlan.requireCompleteSession(false, true, state.copy(manifest = bad), asset) }
