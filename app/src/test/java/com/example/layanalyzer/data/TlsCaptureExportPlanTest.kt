/** Generated bytes and artificial secrets only; no user capture or real TLS traffic. */
class TlsCaptureExportPlanTest {
    @get:Rule val temporary = TemporaryFolder()
    private val captures by lazy { File(temporary.root, "captures") }
    private val privateRoot by lazy { File(temporary.root, "private").apply { mkdirs() } }
    private val work by lazy { File(privateRoot, "bundle-work") }
    private val artifacts by lazy { CaptureArtifactRepository(captures) }
    private val wrapping by lazy {
        val key = KeyGenerator.getInstance("AES").apply { init(256) }.generateKey()
        AesGcmTlsWrappingKeyProvider { key }
    }
    private val secrets by lazy { TlsSecretStore(privateRoot, wrapping) }
    private val bundle by lazy { TlsCaptureBundle(artifacts, secrets, work) }
    private val line = "CLIENT_RANDOM ${"ab".repeat(32)} ${"cd".repeat(48)}\n"
    private val pcap = ByteBuffer.allocate(44).order(ByteOrder.LITTLE_ENDIAN)
        .putInt(0xa1b2c3d4.toInt()).putShort(2).putShort(4).putInt(0).putInt(0).putInt(65535).putInt(1)
        .putInt(1).putInt(0).putInt(4).putInt(4).putInt(123).array()

    private fun seed(): CaptureArtifactManifest {
        val ref = secrets.importRecords("source", KeyLogParser.parse(line.byteInputStream()) as KeyLogParseResult.Success)
        val dir = artifacts.captureDirectory("source").apply { mkdirs() }
        File(dir, "segment.pcap").writeBytes(pcap)
        // Neither arbitrary sibling files nor CA material may be recursively picked up.
        File(dir, "ca-private.pem").writeText("PRIVATE_KEY_SENTINEL")
        File(dir, "unrelated.keys").writeText("SECRET_SENTINEL")
        return artifacts.commit(CaptureArtifactManifest("source",
            segments = listOf(CaptureSegmentRef("segment.pcap", 1, 1)),
            secretsPersistedSequence = ref.watermark.sequence,
            tls = CaptureTlsAssets(enabled = true, secretsAssetId = ref.assetId, complete = true), complete = true))
    }

    private fun exported(): ByteArray {
        seed()
        return ByteArrayOutputStream().also { bundle.writeComplete("source", it, false, true) }.toByteArray()
    }

    private fun entries(bytes: ByteArray): LinkedHashMap<String, ByteArray> {
        val result = linkedMapOf<String, ByteArray>()
        ZipInputStream(bytes.inputStream()).use { zip ->
            while (true) {
                val entry = zip.nextEntry ?: break
                result[entry.name] = zip.readBytes()
            }
        }
        return result
    }

    private fun zip(entries: Map<String, ByteArray>): ByteArray = ByteArrayOutputStream().also { output ->
        ZipOutputStream(output).use { zip ->
            entries.forEach { (name, data) -> zip.putNextEntry(ZipEntry(name)); zip.write(data); zip.closeEntry() }
        }
    }.toByteArray()

    private fun fails(block: () -> Unit) {
        try { block(); fail("Expected rejection") } catch (expected: Exception) { /* no secret exception output */ }
    }

    private fun clean() {
        assertTrue(work.listFiles().orEmpty().isEmpty())
        assertTrue(File(privateRoot, "tls-analysis-leases").listFiles().orEmpty().isEmpty())
        assertFalse(captures.listFiles().orEmpty().any { it.name.startsWith("import-") })
    }

    @Test fun originalIsTheDefaultAndCopiesOnlyRawPackets() {
        seed()
        assertEquals(TlsCaptureExportKind.OriginalCapture, TlsCaptureExportPlan.defaultKind)
        val bytes = ByteArrayOutputStream().also { TlsRawCaptureWriter.copy(pcap.inputStream(), it) }.toByteArray()
        assertArrayEquals(pcap, bytes)
        assertFalse(bytes.toString(Charsets.ISO_8859_1).contains("CLIENT_RANDOM"))
        clean()
    }

    @Test fun publicTls12FixtureExportsTwoSegmentsForIndependentAnalysis() = publicFixture("tls12-h1")
