    @Test fun exportCancellationDuringSecretsClosesLeaseAndDeletesScopedArchive() {
        seed()
        val secretLength = line.length
        var sawSecret = false
        fails {
            bundle.withWorkspace { dir ->
                File(dir, "export.zip").outputStream().use { file ->
                    val sink = object : OutputStream() {
                        override fun write(value: Int) = file.write(value)
                        override fun write(bytes: ByteArray, offset: Int, length: Int) = file.write(bytes, offset, length)
                    }
                    bundle.writeComplete("source", sink, false, true) {
                        val leaseFiles = File(privateRoot, "tls-analysis-leases").walkTopDown()
                            .filter { it.isFile && it.length() == secretLength.toLong() }.toList()
                        if (leaseFiles.isNotEmpty()) { sawSecret = true; throw CancellationException() }
                    }
                }
            }
        }
        assertTrue("Must exercise cancellation after plaintext lease creation", sawSecret)
        clean()
    }

