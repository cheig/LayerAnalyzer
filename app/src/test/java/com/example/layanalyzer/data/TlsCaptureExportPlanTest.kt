    /** Only the already published TLS-002 synthetic fixture is written to ignored build outputs. */
    private fun publicFixture(id: String) {
        val fixtureRoot = File("../native_build/verification/tls/fixtures")
        val fixture = File(fixtureRoot, id)
        val manifest = JSONObject(File(fixtureRoot, "manifest.json").readText()).getJSONArray("fixtures")
        val descriptor = (0 until manifest.length()).map { manifest.getJSONObject(it) }
            .single { it.getString("fixtureId") == id }
        assertEquals("synthetic-local-test-only", descriptor.getString("source"))
        val entries = descriptor.getJSONArray("files")
        for (index in 0 until entries.length()) {
            val entry = entries.getJSONObject(index)
            val bytes = File(fixtureRoot, entry.getString("path")).readBytes()
            assertEquals(entry.getString("sha256"), MessageDigest.getInstance("SHA-256").digest(bytes)
                .joinToString("") { "%02x".format(it.toInt() and 255) })
        }
        val bytes = File(fixture, "capture.pcap").readBytes()
        val header = PcapGlobalHeader.parse(bytes.copyOf(24))
        val records = mutableListOf<ByteArray>()
        var offset = 24
        while (offset < bytes.size) {
            val size = header.unsignedInt(bytes.copyOfRange(offset, offset + 16), 8).toInt() + 16
            records += bytes.copyOfRange(offset, offset + size)
            offset += size
        }
        val parts = listOf(records.take(records.size / 2), records.drop(records.size / 2))
        val dir = artifacts.captureDirectory(id).apply { mkdirs() }
        var next = 1L
        val segments = parts.mapIndexed { index, part ->
            val name = "part-$index.pcap"
            File(dir, name).outputStream().use { output -> output.write(header.raw); part.forEach(output::write) }
            CaptureSegmentRef(name, next, part.size.toLong()).also { next += part.size }
        }
        val parsed = File(fixture, "session.keys").inputStream().use(KeyLogParser::parse) as KeyLogParseResult.Success
        val ref = secrets.importRecords(id, parsed)
        artifacts.commit(CaptureArtifactManifest(id, segments = segments, complete = true,
            secretsPersistedSequence = ref.watermark.sequence,
            tls = CaptureTlsAssets(enabled = true, secretsAssetId = ref.assetId, complete = true)))
        val exported = ByteArrayOutputStream().also { bundle.writeComplete(id, it, false, true) }.toByteArray()
        val importedId = bundle.importComplete(exported.inputStream())
        val merged = artifacts.openForAnalysis(importedId) as CaptureAnalysisSource.Merged
        assertFalse(merged.contextIncomplete)
        assertArrayEquals(bytes, merged.analysisFile.readBytes())
        val outputDir = File("build/tls-311").apply { mkdirs() }
        File(outputDir, "$id.zip").writeBytes(exported)
    }

    @Test fun fullBundleIsWhitelistedAndHasNoLocalSecretPathOrPrivateKey() {
        val files = entries(exported())
        assertEquals(setOf("packets-0001.pcap", "keys.log", "manifest.json", "checksums.json"), files.keys)
        assertArrayEquals(pcap, files.getValue("packets-0001.pcap"))
        assertEquals(line, files.getValue("keys.log").toString(Charsets.US_ASCII))
        val manifest = JSONObject(files.getValue("manifest.json").toString(Charsets.UTF_8))
        assertTrue(manifest.getJSONObject("tls").isNull("secretsAssetId"))
        assertFalse(files.values.any { it.toString(Charsets.UTF_8).contains("SENTINEL") })
        clean()
    }

    @Test fun freshStoreRoundTripRebindsIdsAndPreservesPcapAndKeylog() {
        val bytes = exported()
        val target = File(temporary.root, "target")
        val targetArtifacts = CaptureArtifactRepository(File(target, "captures"))
        val targetKey = KeyGenerator.getInstance("AES").apply { init(256) }.generateKey()
        val targetSecrets = TlsSecretStore(File(target, "private").apply { mkdirs() }, AesGcmTlsWrappingKeyProvider { targetKey })
        val targetWork = File(target, "private/work")
        val targetBundle = TlsCaptureBundle(targetArtifacts, targetSecrets, targetWork)
        val id = targetBundle.importComplete(bytes.inputStream())
        assertNotEquals("source", id)
        val state = targetArtifacts.read(id) as CaptureArtifactState.Present
        assertTrue(state.isComplete)
        assertArrayEquals(pcap, targetArtifacts.resolveSegment(id, state.manifest.segments.single()).readBytes())
        assertNotEquals(secrets.currentAsset("source")!!.assetId, state.manifest.tls.secretsAssetId)
        // Recreate the store to exercise persisted wrapped-key binding, not an in-memory cache.
        val reopened = TlsSecretStore(File(target, "private"), AesGcmTlsWrappingKeyProvider { targetKey })
        reopened.acquireLease(id, state.manifest.tls.secretsAssetId).use { lease ->
            val output = ByteArrayOutputStream()
            lease.copyForExplicitExport(output) {}
            assertEquals(line, output.toString("US-ASCII"))
        }
        assertTrue(targetWork.listFiles().orEmpty().isEmpty())
    }

