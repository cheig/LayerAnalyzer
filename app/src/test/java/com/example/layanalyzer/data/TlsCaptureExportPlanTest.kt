    @Test fun rawPcapngRemovesSecretsInBothByteOrdersAndResetsSectionLength() {
        fun section(order: ByteOrder): ByteArray = ByteBuffer.allocate(28).order(order)
            .putInt(0x0a0d0d0a).putInt(28).putInt(0x1a2b3c4d).putShort(1).putShort(0).putLong(100).putInt(28).array()
        fun block(type: Int, data: ByteArray, order: ByteOrder): ByteArray = ByteBuffer.allocate(data.size + 12).order(order)
            .putInt(type).putInt(data.size + 12).put(data).putInt(data.size + 12).array()
        val expected = ByteArrayOutputStream()
        val input = ByteArrayOutputStream()
        for (order in listOf(ByteOrder.LITTLE_ENDIAN, ByteOrder.BIG_ENDIAN)) {
            input.write(section(order))
            input.write(block(10, "SECRET!!".toByteArray(), order))
            val packet = block(3, byteArrayOf(4, 0, 0, 0, 1, 2, 3, 4), order)
            input.write(packet)
            expected.write(section(order).also { ByteBuffer.wrap(it).order(order).putLong(16, -1) })
            expected.write(packet)
        }
        val output = ByteArrayOutputStream()
        assertEquals(2L, TlsRawCaptureWriter.copy(input.toByteArray().inputStream(), output))
        assertArrayEquals(expected.toByteArray(), output.toByteArray())
        assertFalse(output.toString("US-ASCII").contains("SECRET"))
    }

    @Test fun truncatedAndOversizedRawRecordsAreRejected() {
        for (bytes in listOf(pcap.copyOf(43), pcap.copyOf().also {
            ByteBuffer.wrap(it).order(ByteOrder.LITTLE_ENDIAN).putInt(32, Int.MAX_VALUE)
        })) fails { TlsRawCaptureWriter.copy(bytes.inputStream(), ByteArrayOutputStream()) }
    }

    private fun rehash(files: MutableMap<String, ByteArray>) {
        val checksums = JSONObject()
        for ((name, bytes) in files) if (name != "checksums.json") {
            val hash = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it.toInt() and 255) }
            checksums.put(name, JSONObject().put("bytes", bytes.size).put("sha256", hash))
        }
        files["checksums.json"] = JSONObject().put("schemaVersion", 1).put("files", checksums).toString().toByteArray()
    }
