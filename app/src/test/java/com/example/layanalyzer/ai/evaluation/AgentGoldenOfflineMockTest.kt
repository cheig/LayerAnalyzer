    @Test
    fun `grouped finding hit rates measure the new families against the baseline`() {
        val summary = evaluateOfflineGoldenSet().summary
        val groups = summary.scenarioGroups

        assertEquals(
            listOf(
                GoldenScenarioGrouping.BASELINE_GROUP_ID,
                GoldenScenarioGrouping.TRANSPORT_GROUP_ID,
                GoldenScenarioGrouping.APPLICATION_GROUP_ID
            ),
            groups.map { it.groupId }
        )

        val baseline = groups.first { it.groupId == GoldenScenarioGrouping.BASELINE_GROUP_ID }
        assertEquals(9, baseline.scenarioCount)
        assertEquals(9, baseline.runs)
        // ims_call_success expects two findings; every other family expects one.
        assertEquals(10, baseline.expectedFindingCount)
        assertEquals(10, baseline.findingHits)
        assertEquals(1.0, baseline.findingHitRate, 0.0)

        val transport = groups.first { it.groupId == GoldenScenarioGrouping.TRANSPORT_GROUP_ID }
        assertEquals(4, transport.scenarioCount)
        assertEquals(4, transport.runs)
        assertEquals(4, transport.expectedFindingCount)
        assertEquals(4, transport.findingHits)
        assertEquals(1.0, transport.findingHitRate, 0.0)
        assertEquals(1.0, transport.evidenceFramePrecision, 0.0)
        assertEquals(1.0, transport.evidenceFrameRecall, 0.0)
        assertEquals(4, transport.passedScenarioCount)

        val application = groups.first { it.groupId == GoldenScenarioGrouping.APPLICATION_GROUP_ID }
        assertEquals(3, application.scenarioCount)
        assertEquals(3, application.runs)
        assertEquals(3, application.expectedFindingCount)
        assertEquals(3, application.findingHits)
        assertEquals(1.0, application.findingHitRate, 0.0)
        assertEquals(1.0, application.evidenceFramePrecision, 0.0)
        assertEquals(1.0, application.evidenceFrameRecall, 0.0)
        assertEquals(3, application.passedScenarioCount)

        // §9.2 gate 8 shape: every extension group is comparable to, and not
        // below, the baseline group, and the group sums equal the overall rate.
        assertTrue(transport.findingHitRate >= baseline.findingHitRate)
        assertTrue(application.findingHitRate >= baseline.findingHitRate)
        assertEquals(summary.findingHitRate, 1.0, 0.0)
    }

