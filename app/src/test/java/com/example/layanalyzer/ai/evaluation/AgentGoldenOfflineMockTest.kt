/**
 * OPT-EVAL-01-02 (extended by OPT-EVAL-01-03): offline Mock wiring of the
 * sixteen-family golden set.
 *
 * Replays every generated mock transcript through [AgentEvaluationRunner]
 * without the native engine, so the JVM suite pins that (a) every family —
 * the nine AI-19 IMS/SIP scenarios, the four transport families from
 * OPT-EVAL-01-01 and the three application-layer families from
 * OPT-EVAL-01-03 — hits its expected findings, satisfies its per-finding
 * required evidence frames, stays clear of its forbidden conclusions and
 * declares its boundary limitations under the existing runner semantics, and
 * (b) the §9.2 gate 8 grouping aggregates are measurable: a
 * `findingHitRate` for each extension group and one for the baseline group,
 * computed with the very same formula as the overall figure.
 *
 * Offline frame crediting: a transcript only scripts the model side, so the
 * harness assumes the last scripted tool call returned exactly the capture's
 * expectation-pinned evidence frames (top-level `requiredEvidenceFrames` plus
 * every expected finding's frames).  Citations outside that set stay invalid,
 * so evidence validation still has teeth. Capture bytes and expected findings
 * remain pinned; transcripts are regenerated by the golden-capture tool.
 */
class AgentGoldenOfflineMockTest {

    @Test
    fun `the offline golden roster covers sixteen families in three pinned groups`() {
        val ids = expectations().map { it.id }
        assertEquals(16, ids.size)
        assertEquals(
            "Every generated expectation must be replayed by a generated transcript.",
            ids.sorted(),
            ids.mapNotNull { id ->
                if (transcriptFile(id).isFile) id else null
            }.sorted()
        )
        assertEquals(BASELINE_FAMILY_IDS.toSet(), ids.filter {
            GoldenScenarioGrouping.groupOf(it) == GoldenScenarioGrouping.BASELINE_GROUP_ID
        }.toSet())
        assertEquals(TRANSPORT_FAMILY_IDS.toSet(), ids.filter {
            GoldenScenarioGrouping.groupOf(it) == GoldenScenarioGrouping.TRANSPORT_GROUP_ID
        }.toSet())
        assertEquals(APPLICATION_FAMILY_IDS.toSet(), ids.filter {
            GoldenScenarioGrouping.groupOf(it) == GoldenScenarioGrouping.APPLICATION_GROUP_ID
        }.toSet())
        assertTrue(
            "No golden family may fall through to the unassigned bucket.",
            ids.none { GoldenScenarioGrouping.groupOf(it) == GoldenScenarioGrouping.UNASSIGNED_GROUP_ID }
        )
    }

    @Test
    fun `every golden family hits all expected findings in one offline mock run`() {
        val evaluation = evaluateOfflineGoldenSet()

        assertEquals(16, evaluation.scenarios.size)
        evaluation.scenarios.forEach { scenario ->
            val expectation = expectationsById().getValue(scenario.scenarioId)
            assertTrue("${scenario.scenarioId} must also cover the scenario-level evidence and pass", scenario.passed)
            assertEquals("One replayed run per family.", 1, scenario.runs)
            assertEquals(
                "${scenario.scenarioId} must hit every expected finding.",
                expectation.expectedFindings.size,
                scenario.findingHits
            )
            assertEquals("${scenario.scenarioId} must stay clear of forbidden conclusions.",
                0, scenario.forbiddenConclusionHits)
            assertEquals("${scenario.scenarioId} must not over-claim.",
                0, scenario.unsupportedHighConfidenceFindings)
            assertEquals("${scenario.scenarioId} must declare its boundary.",
                1, scenario.boundaryDeclarations)
            assertEquals("Each golden transcript scripts two tool calls.",
                2.0, scenario.averageToolCalls, 0.0)
            assertTrue(
                "${scenario.scenarioId} must stay inside its tool-call budget.",
                scenario.averageToolCalls <= expectation.maximumToolCalls
            )
        }
    }

